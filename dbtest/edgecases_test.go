func run(t *testing.T, db bun.IDB, stmts ...string) {
	t.Helper()
	for _, stmt := range stmts {
		if _, err := db.ExecContext(context.Background(), stmt); err != nil {
			t.Fatalf("%s: %v", stmt, err)
		}
	}
}

// insertPlan is a change set that inserts one plan with an explicit id into a
// serial table.
func insertPlan(table, name, id string) fixturechange.Set {
	return fixturechange.Set{
		Name:   "20260921120000_fixture_sequence",
		Tables: fixturechange.Tables{"Plan": {Name: table, ID: "id", Key: "name", Serial: true}},
		Changes: []fixturechange.Change{{Model: "Plan", Kind: fixturechange.Insert,
			Key: fixturechange.Values{"name": fixturechange.Lit(name)},
			New: fixturechange.Values{"id": fixturechange.Lit(id), "name": fixturechange.Lit(name)}}},
	}
}

// setval is not transactional, so a sequence moved back to the highest id
// hands out again the values other sessions already drew, and deleted ids.
// Before: an explicit id 10 into a table whose sequence stood at 100 set it to
// 10, and the next ordinary insert got 11.
func TestASequenceIsNeverMovedBack(t *testing.T) {
	db := connect(t)
	ctx := context.Background()
	run(t, db,
		"DROP TABLE IF EXISTS seq_plans",
		"CREATE TABLE seq_plans (id bigserial PRIMARY KEY, name text UNIQUE NOT NULL)",
		"INSERT INTO seq_plans (name) VALUES ('a'), ('b'), ('c')",
		"SELECT setval('seq_plans_id_seq', 100)")
	if err := fixtureapply.Apply(ctx, db, insertPlan("seq_plans", "x", "10"), quiet()); err != nil {
		t.Fatal(err)
	}
	if got := scan[int64](t, db, "SELECT last_value FROM seq_plans_id_seq"); got != 100 {
		t.Fatalf("the sequence was moved from 100 to %d", got)
	}
	// Behind the ids written, it is moved forward.
	if err := fixtureapply.Apply(ctx, db, insertPlan("seq_plans", "y", "500"), quiet()); err != nil {
		t.Fatal(err)
	}
	if got := scan[int64](t, db, "SELECT last_value FROM seq_plans_id_seq"); got != 500 {
		t.Fatalf("the sequence should stand at 500, got %d", got)
	}
}

