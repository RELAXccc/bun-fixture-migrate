// dbfixture writes explicit ids and a sequence does not see them go by, so
// the application's first insert after seeding failed on the primary key.
// SyncSequences finds every serial and identity column, whatever its name or
// the table's case, and moves only what is behind.
func TestSyncSequencesAfterSeeding(t *testing.T) {
	db := connect(t)
	ctx := context.Background()
	run(t, db,
		`DROP TABLE IF EXISTS "SeedPlans", seed_items`,
		`CREATE TABLE "SeedPlans" ("PlanID" bigserial PRIMARY KEY, name text UNIQUE NOT NULL)`,
		`CREATE TABLE seed_items (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, `+
			`pos serial, label text)`,
		`INSERT INTO "SeedPlans" ("PlanID", name) VALUES (1, 'a'), (2, 'b')`,
		`INSERT INTO seed_items (id, pos, label) VALUES (40, 3, 'x')`,
		`SELECT setval('seed_items_pos_seq', 90)`)
	moved, err := fixtureapply.SyncSequences(ctx, db, "SeedPlans", "seed_items")
	if err != nil {
		t.Fatal(err)
	}
	if strings.Join(moved, ",") != "SeedPlans.PlanID,seed_items.id" {
		t.Fatalf("moved %v; pos stood at 90, ahead of 3, and stays", moved)
	}
	run(t, db, `INSERT INTO "SeedPlans" (name) VALUES ('c')`, `INSERT INTO seed_items (label) VALUES ('y')`)
	if got := scan[int64](t, db, `SELECT "PlanID" FROM "SeedPlans" WHERE name = 'c'`); got != 3 {
		t.Fatalf("next plan id %d", got)
	}
	if got := scan[string](t, db, `SELECT id || '/' || pos FROM seed_items WHERE label = 'y'`); got != "41/91" {
		t.Fatalf("next item %s", got)
	}
	if moved, err := fixtureapply.SyncSequences(ctx, db, "SeedPlans", "seed_items"); err != nil || len(moved) != 0 {
		t.Fatalf("a second call has nothing to do: %v %v", moved, err)
	}
	if _, err := fixtureapply.SyncSequences(ctx, db, "no_such_table"); err == nil {
		t.Fatal("an unknown table is an error, not nothing to do")
	}
	if _, err := fixtureapply.SyncSequences(ctx, db, "x; DROP TABLE seed_items"); err == nil {
		t.Fatal("a table name is an identifier")
	}
}

// A dry run leaves the sequence where it was, since a rollback cannot move it
// back, and reports what the migration would do instead.
func TestADryRunLeavesTheSequenceAlone(t *testing.T) {
	db := connect(t)
	ctx := context.Background()
	run(t, db,
		"DROP TABLE IF EXISTS seq_plans",
		"CREATE TABLE seq_plans (id bigserial PRIMARY KEY, name text UNIQUE NOT NULL)",
		"INSERT INTO seq_plans (name) VALUES ('a')")
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	var outcomes []fixtureapply.Outcome
	err = fixtureapply.Apply(ctx, tx, insertPlan("seq_plans", "x", "50"), quiet(), fixtureapply.WithDryRun(),
		fixtureapply.WithReport(func(o fixtureapply.Outcome) { outcomes = append(outcomes, o) }))
	if err != nil {
		t.Fatal(err)
	}
	if err := tx.Rollback(); err != nil {
		t.Fatal(err)
	}
	if got := scan[int64](t, db, "SELECT last_value FROM seq_plans_id_seq"); got != 1 {
		t.Fatalf("a dry run moved the sequence to %d", got)
	}
	last := outcomes[len(outcomes)-1]
	if last.Status != fixtureapply.StatusSequence || !strings.Contains(last.Message, "a dry run leaves alone") {
		t.Fatalf("the sequence step has to be reported: %+v", outcomes)
	}
}

